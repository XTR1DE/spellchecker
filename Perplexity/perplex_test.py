def print_section(title):
    print("\n" + "=" * 72)
    print(title)
    print("=" * 72)


def print_word(info):
    """Печатает слово, варианты исправления, их NLL и решение."""
    if info["best_word"] is None:
        print(f"    {info['word']}: подходящих вариантов нет")
        return

    decision = "ИСПРАВЛЕНО" if info["fixed"] else "оставлено"
    print(f"    {info['word']}: {decision} | NLL исходного слова {info['original_nll']:.2f}")
    for candidate, score, gain in info["candidates"][:5]:
        print(f"        {candidate:<24} NLL={score:8.2f}  выигрыш {gain:+.2f}")


def check_batch():
    """Проверка оптимизации: NLL в батче должен совпадать с NLL по одному тексту."""
    texts = ["Сервер не отвечал на запросы.", "Сервер.", "Аналитик работал на сервере и изучил логи."]
    together = spellchecker.nll_batch(texts)
    alone = [spellchecker.nll_batch([text])[0] for text in texts]
    diff = max(abs(a - b) for a, b in zip(together, alone))
    print(f"Проверка батчей: максимальная разница NLL {diff:.4f} (должна быть около 0)")


def main():
    start = time.perf_counter()
    spellchecker.load_model()
    load_time = time.perf_counter() - start

    check_batch()

    # Прогон всех примеров.
    start = time.perf_counter()
    results = []
    for source, expected in SAMPLES:
        corrected, logs = spellchecker.check(source)
        results.append((source, expected, corrected, logs))
    check_time = time.perf_counter() - start

    # Подсчёт: сравниваем слова исходного и ожидаемого текста попарно.
    typos_total = 0         # всего опечаток в тестах
    typos_checked = 0       # из них дошли до модели
    fixed_right = 0         # исправлено верно
    fixed_wrong = 0         # исправлено, но не тем вариантом
    right_but_weak = 0      # нужный вариант лучший, но выигрыш ниже порога
    wrong_best = 0          # лучший вариант не тот, исправления нет
    no_candidates = 0       # подходящих вариантов нет
    typo_gains = []         # выигрыш нужного варианта у опечаток
    clean_gains = []        # выигрыш лучшего варианта у корректных слов
    false_fixes = []        # (слово, на что заменили, выигрыш)
    nll_texts = 0

    for source, expected, corrected, logs in results:
        want = dict(zip(re.findall(WORD, source), re.findall(WORD, expected)))
        typos_total += sum(1 for word, right in want.items() if word != right)

        for info in logs:
            word = info["word"]
            right = want[word]
            nll_texts += len(info["candidates"]) + 1 if info["candidates"] else 0

            if right != word:
                typos_checked += 1
                if info["best_word"] is None:
                    no_candidates += 1
                elif info["best_word"] != right:
                    if info["fixed"]:
                        fixed_wrong += 1
                    else:
                        wrong_best += 1
                else:
                    typo_gains.append(info["gain"])
                    if info["fixed"]:
                        fixed_right += 1
                    else:
                        right_but_weak += 1
            elif info["best_word"] is not None:
                clean_gains.append(info["gain"])
                if info["fixed"]:
                    false_fixes.append((word, info["best_word"], info["gain"]))

    passed = sum(1 for _, expected, corrected, _ in results if corrected == expected)

    # Подробности: только расхождения (или все слова, если VERBOSE).
    print_section("РАСХОЖДЕНИЯ С ОЖИДАЕМЫМ РЕЗУЛЬТАТОМ")
    for source, expected, corrected, logs in results:
        if corrected == expected and not VERBOSE:
            continue
        status = "✓" if corrected == expected else "✗"
        print(f"\n{status} {source}")
        if corrected != expected:
            print(f"  получили:  {corrected}")
            print(f"  ожидалось: {expected}")
        for info in logs:
            print_word(info)
    if passed == len(results) and not VERBOSE:
        print("Расхождений нет.")

    print_section("ВЫВОДЫ")
    print(f"Предложений: {len(results)}, совпало с ожидаемым: {passed} ({passed / len(results):.0%})")
    print(f"Порог MARGIN: {spellchecker.MARGIN:.2f} nats")

    print("\nОпечатки")
    print(f"  всего в тестах:                                {typos_total}")
    print(f"  дошли до модели:                               {typos_checked}")
    print(f"    исправлены верно:                            {fixed_right}")
    print(f"    нужный вариант лучший, но выигрыш < порога:  {right_but_weak}")
    print(f"    лучший вариант не тот, исправления нет:      {wrong_best}")
    print(f"    исправлены неверным вариантом:               {fixed_wrong}")
    print(f"    нет подходящих вариантов в словаре:          {no_candidates}")
    print(f"  не дошли до модели (слово есть в словаре или короче {spellchecker.MIN_LEN}): "
          f"{typos_total - typos_checked}")

    print("\nКорректные слова, которых нет в словаре pymorphy3 (жаргон, названия)")
    print(f"  дошли до модели с вариантами:  {len(clean_gains)}")
    print(f"  ложных исправлений:            {len(false_fixes)}")
    for word, new_word, gain in false_fixes:
        print(f"    {word} -> {new_word} (выигрыш {gain:+.2f})")

    print("\nКак оценки модели разделяют опечатки и корректные слова")
    if typo_gains:
        print(f"  выигрыш нужного варианта у опечаток: "
              f"мин {min(typo_gains):+.2f}, медиана {median(typo_gains):+.2f}, макс {max(typo_gains):+.2f}")
    if clean_gains:
        print(f"  выигрыш лучшего варианта у корректных слов: "
              f"медиана {median(clean_gains):+.2f}, макс {max(clean_gains):+.2f}")
    if typo_gains and clean_gains:
        overlap = sum(1 for gain in clean_gains if gain >= min(typo_gains))
        if overlap == 0:
            print(f"  Вывод: диапазоны не пересекаются, порог между {max(clean_gains):+.2f} "
                  f"и {min(typo_gains):+.2f} разделяет их без ошибок.")
        else:
            print(f"  Вывод: диапазоны пересекаются, {overlap} корректных слов имеют выигрыш не ниже "
                  f"самой слабой верной опечатки; порог придётся выбирать между точностью и полнотой.")

    print("\nПримечание: сравнивается суммарный NLL одного и того же текста с разными словами, "
          "поэтому разная длина вариантов в токенах не искажает сравнение (perplexity на токен исказила бы).")

    print("\nСкорость")
    print(f"  загрузка модели:   {load_time:.2f} сек.")
    print(f"  проверка тестов:   {check_time:.2f} сек. ({check_time / len(results) * 1000:.0f} мс на предложение)")
    print(f"  оценено текстов:   {nll_texts}")


if __name__ == "__main__":
    main()